"""Reports committed with the code: what the agents score per customer, where each process waits, and the
portfolio view. Generated by `rdw report`; not edited by hand."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .service import Workbench


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.1%}"


def write_reports(wb: Workbench, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    data: dict[str, Any] = {"customers": {}}
    md = [
        "# Workbench report",
        "",
        "Generated by `rdw report` from the simulated customers (`rdw-sim`); do not edit by hand.",
        "Scores are on the customers' past tenders, which the agents were developed against. Held-out results, on "
        "tenders written by someone who never saw the code, are in `reports/heldout/`.",
        "",
    ]
    for cid in wb.customers():
        d = wb.deployment(cid)
        ev = wb.evaluation(cid)
        disc = wb.discovery(cid)
        v = wb.value(cid)
        data["customers"][cid] = {
            "stage": d["stage"],
            "health": d["health"],
            "metrics": ev["metrics"],
            "readiness": {k: r["level"] for k, r in ev["readiness"].items()},
            "bottleneck": disc["bottleneck"],
            "lead_time_days": disc["lead_time_days"],
            "value": {
                k: v[k]
                for k in ("hours_per_year", "capacity_people", "gross_per_year", "net_per_year", "lead_time_days")
            },
        }
        md += [
            f"## {d['customer']['name']} ({d['stage']}, {d['health']})",
            "",
            wb.summary(cid, d, v),
            "",
            "| Agent | Readiness | Key metric | Right | Lower bound |",
            "| --- | --- | --- | --- | --- |",
        ]
        for r in ev["readiness"].values():
            md.append(
                f"| {r['label']} | {r['level'].replace('_', ' ')} | {r['metric'].replace('_', ' ')} | {r['right']}/{r['of']} | {_pct(r['lower_bound'])} |"
            )
        b = disc["bottleneck"]
        md += [
            "",
            f"Quote process: {disc['cases']} tenders in {disc['period_days']} days, median {disc['lead_time_days']['median']} days "
            f"to bid; most waiting before *{b['activity']}* ({b['kind']}, {b['wait_hours_per_case']} hours per tender).",
            "",
        ]
    for h in wb.heldout():
        names = list(h["customers"])
        md += [
            f"## Held-out set {h['set']} ({h['status']}, first run {h['run_at'][:10]})",
            "",
            "Tenders written by someone who never saw the code; these are the scores to quote.",
            "",
            "| Measure | " + " | ".join(names) + " |",
            "| --- |" + " --- |" * len(names),
        ]
        for key in ("requirement_recall", "red_flag_recall", "verdict_accuracy", "bid_accuracy", "unsafe_bid_avoided"):
            cells = []
            for c in names:
                m = h["customers"][c]["metrics"].get(key)
                cells.append(f"{m['right']}/{m['of']} ({_pct(m['rate'])})" if m else "n/a")
            md.append(f"| {key.replace('_', ' ')} | " + " | ".join(cells) + " |")
        md.append("")
        data.setdefault("heldout", []).append(h)
    p = wb.portfolio()
    md += [
        "## Across customers",
        "",
        "Shared requirement kinds (core platform): " + ", ".join(p["shared_kinds"]) + ".",
        "",
        "| Platform backlog | Cause | Customers | Count |",
        "| --- | --- | --- | --- |",
    ]
    for b in p["platform_backlog"][:10]:
        md.append(f"| {b['agent']}: {b['kind']} | {b['cause']} | {', '.join(b['customers'])} | {b['count']} |")
    paths = [out / "WORKBENCH.md", out / "workbench.json"]
    paths[0].write_text("\n".join(md) + "\n", encoding="utf-8")
    paths[1].write_text(json.dumps(data, indent=1, default=str), encoding="utf-8")
    return paths
